#!/bin/bash

set -e

SCENARIO=$1
BASE="/home/cc/netprompt-milestone-II"
PY="/usr/bin/python3"

if [ -z "$SCENARIO" ]; then
    echo "Usage: ./timed_netprompt_runner.sh <scenario>"
    exit 1
fi

mkdir -p "$BASE/timing_logs"
mkdir -p "$BASE/comparative_results"

OUT="$BASE/comparative_results/proposed_netprompt_${SCENARIO}.txt"
RUN_LOG="$BASE/timing_logs/proposed_run_${SCENARIO}.log"
METRICS_FILE="$BASE/timing_logs/proposed_metrics_${SCENARIO}.env"

T0=$(date +%s.%N)

S0=$(date +%s.%N)
$PY "$BASE/experiments/update_topology_state.py" "$SCENARIO"
E0=$(date +%s.%N)

S1=$(date +%s.%N)
SELECTION_JSON=$($PY "$BASE/experiments/path_aware_sfc_selector.py" "$SCENARIO")
E1=$(date +%s.%N)

SFC=$(echo "$SELECTION_JSON" | $PY -c "import sys,json; print(json.load(sys.stdin).get('selected_sfc','NA'))")
SELECTED_PATH=$(echo "$SELECTION_JSON" | $PY -c "import sys,json; print(json.load(sys.stdin).get('selected_path','NA'))")
RELAY=$(echo "$SELECTION_JSON" | $PY -c "import sys,json; print(json.load(sys.stdin).get('selected_relay','NA'))")

S2=$(date +%s.%N)
"$BASE/experiments/run_netprompt_milestone2_final.sh" "$SCENARIO" | tee "$RUN_LOG"
E2=$(date +%s.%N)

S3=$(date +%s.%N)
cd "$BASE/results"
$PY parse_and_push_final_results.py
E3=$(date +%s.%N)

T1=$(date +%s.%N)

KG_TIME=$($PY -c "print(round($E0-$S0,6))")
SELECT_TIME=$($PY -c "print(round($E1-$S1,6))")
DEPLOY_TIME=$($PY -c "print(round($E2-$S2,6))")
RESULT_TIME=$($PY -c "print(round($E3-$S3,6))")
TOTAL_TIME=$($PY -c "print(round($T1-$T0,6))")

RESULT_TXT=$(grep -E "Results saved to " "$RUN_LOG" | tail -n 1 | sed 's/.*Results saved to //')

if [ -z "$RESULT_TXT" ] || [ ! -f "$RESULT_TXT" ]; then
    RESULT_TXT=$(find "$BASE/results" -type f -name "*${SCENARIO}*${SFC}*.txt" | sort | tail -n 1)
fi

$PY - "$RESULT_TXT" "$SCENARIO" "$BASE/results/final_milestone2_results_clean.csv" > "$METRICS_FILE" <<'PYCODE'
import sys
import re
import csv
from pathlib import Path

result_txt = Path(sys.argv[1]) if len(sys.argv) > 1 and sys.argv[1] else None
scenario = sys.argv[2]
clean_csv = Path(sys.argv[3])

metrics = {
    "RESULT_FILE": str(result_txt) if result_txt else "",
    "CONFIGURED_BW": "NA",
    "CONFIGURED_DELAY": "NA",
    "CONFIGURED_LOSS": "NA",
    "RTT_AVG": "NA",
    "THROUGHPUT": "NA",
    "MEASURED_PACKET_LOSS": "NA",
    "POLICY_TYPE": "NA",
}

text = ""
if result_txt and result_txt.exists():
    text = result_txt.read_text(errors="ignore")

def search(pattern, default="NA"):
    m = re.search(pattern, text, re.MULTILINE)
    return m.group(1).strip() if m else default

# Try raw result text first.
metrics["CONFIGURED_BW"] = search(r"Configured Bandwidth(?: Mbps)?:\s*([\d.]+)", metrics["CONFIGURED_BW"])
metrics["CONFIGURED_DELAY"] = search(r"Configured Delay:\s*([^\n]+)", metrics["CONFIGURED_DELAY"])
metrics["CONFIGURED_LOSS"] = search(r"Configured Loss(?: Percent)?:\s*([\d.]+)", metrics["CONFIGURED_LOSS"])
metrics["POLICY_TYPE"] = search(r"Policy Type:\s*([^\n]+)", metrics["POLICY_TYPE"])

rtt = re.search(r"rtt min/avg/max/mdev = [\d.]+/([\d.]+)/[\d.]+/[\d.]+", text)
if rtt:
    metrics["RTT_AVG"] = rtt.group(1)

thr = re.findall(r"([\d.]+)\s+Mbits/sec", text)
if thr:
    metrics["THROUGHPUT"] = thr[-1]

loss = re.search(r"\*\*\* Results:\s*([\d.]+)% dropped", text)
if loss:
    metrics["MEASURED_PACKET_LOSS"] = loss.group(1)

# Fall back to parsed CSV generated by your existing parser.
if clean_csv.exists():
    with clean_csv.open(newline="") as f:
        rows = list(csv.DictReader(f))

    candidates = [r for r in rows if r.get("scenario") == scenario]

    # Prefer the newly generated source file when possible.
    if result_txt:
        candidates2 = [r for r in candidates if r.get("source_file") == result_txt.name]
        if candidates2:
            candidates = candidates2

    # Otherwise prefer multihop for multihop result files, else dynamic.
    if candidates:
        row = candidates[-1]
        for key, csv_key in [
            ("CONFIGURED_BW", "configured_bandwidth_mbps"),
            ("CONFIGURED_DELAY", "configured_delay"),
            ("CONFIGURED_LOSS", "configured_loss_percent"),
            ("RTT_AVG", "rtt_avg_ms"),
            ("THROUGHPUT", "throughput_mbps"),
            ("MEASURED_PACKET_LOSS", "measured_packet_loss_percent"),
            ("POLICY_TYPE", "policy_type"),
        ]:
            if metrics[key] in ["", "NA", "None", "null"]:
                value = row.get(csv_key, "")
                if value not in ["", "None", "null", None]:
                    metrics[key] = value

for k, v in metrics.items():
    print(f'{k}="{v}"')
PYCODE

source "$METRICS_FILE"

cat > "$OUT" <<EOF
Method: Proposed KG-Driven NetPrompt
Scenario: $SCENARIO
Selected SFC: $SFC
Selected Path: $SELECTED_PATH
Selected Relay: $RELAY
KG Used: Yes
Path Reasoning Used: Yes
Policy Type: $POLICY_TYPE
Configured Bandwidth Mbps: $CONFIGURED_BW
Configured Delay: $CONFIGURED_DELAY
Configured Loss Percent: $CONFIGURED_LOSS
RTT Average ms: $RTT_AVG
Throughput Mbps: $THROUGHPUT
Measured Packet Loss Percent: $MEASURED_PACKET_LOSS
KG Update Seconds: $KG_TIME
Path-Aware SFC Selection Seconds: $SELECT_TIME
Policy Deployment Experiment Seconds: $DEPLOY_TIME
Result Push Seconds: $RESULT_TIME
Total Pipeline Seconds: $TOTAL_TIME
Result File: $RESULT_FILE
EOF

echo "[OK] Saved $OUT"
